def load(root):
    """Returns (ui, {slug: {lang: data}}, errors). Missing folder = no translations."""
    base = Path(root).joinpath(*I18N_DIR)
    ui, tr, errs = {}, {}, []
    if not base.is_dir():
        return ui, tr, errs
    f = base / "ui.json"
    if f.is_file():
        try:
            ui = json.loads(f.read_text(encoding="utf-8"))
        except ValueError as e:
            errs.append("journal_i18n/ui.json invalid: %s" % e)
    for d in sorted(p for p in base.iterdir() if p.is_dir()):
        for lang in TR_LANGS:
            f = d / ("%s.json" % K.legacy_code(lang))
            if not f.is_file():
                continue
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
            except ValueError as e:
                errs.append("journal_i18n/%s/%s.json invalid: %s" % (d.name, lang, e))
                continue
            e = check_post_data("journal_i18n/%s/%s.json" % (d.name, lang), data)
            if e:
                errs += e
                continue
            tr.setdefault(d.name, {})[lang] = data
    return ui, tr, errs


def check_post_data(label, data):
    """Errors for one language's post data dict (shared by en/ko sources and translation JSON)."""
    errs = []
    missing = [k for k in POST_KEYS if not str(data.get(k, "")).strip()]
    if missing:
        errs.append("%s missing %s" % (label, ", ".join(missing)))
    elif "<script" in data["body"].lower() or "<script" in data["h1_html"].lower():
        errs.append("%s contains <script>" % label)
    return errs


def ui_errors(ui, langs):
    """(errors, bad_langs): every language used needs the UI strings (AI-note keys only for machine-translated ones)."""
    errs, bad = [], set()
    for lang in LANGS:
        if lang not in langs:
            continue
        keys = UI_KEYS + (AI_KEYS if lang in TR_LANGS else ()) + (NT_KEYS if lang in NO_POST_TRANSLATION else ())
        miss = [k for k in keys if not str(ui.get(lang, {}).get(k, "")).strip()]
        if miss:
            bad.add(lang)
            errs.append("journal_i18n/ui.json[%s] missing %s" % (lang, ", ".join(miss)))
    return errs, bad


def words(lang, body_html):
    """wordCount for a translation: whitespace words, or non-space characters for zh/ja (no word spaces)."""
    import re
    text = html.unescape(re.sub(r"<[^>]+>", " ", body_html))
    if lang in ("zh", "ja"):
        return len(re.sub(r"\s+", "", text))
    return len(text.split())


