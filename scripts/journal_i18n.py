"""Journal translations (10 languages) for ipe.rest — stdlib only. Used by journal_sync.py.

URL rule (static, never ?lang=):
    original (EN+KO in one file)   /journal/<slug>/            (?lang=en / ?lang=ko stay as they are)
    translation                    /journal/<lang>/<slug>/     lang = ja zh es fr de pt ru ar hi id
    translated list page           /journal/<lang>/

Source data (hand/machine-drafted, one file per post+language, plus UI strings):
    scripts/journal_i18n/ui.json
    scripts/journal_i18n/<slug>/<lang>.json   title, description, abstract, excerpt, h1_html, body (HTML), [keywords, dateModified]

Everything under journal/<lang>/ is GENERATED by journal_sync.py from those files — never edit it by hand.
"""
import html
import json
from pathlib import Path

SITE = "https://ipe.rest"
ORG_ID = SITE + "/#organization"
VER_CSS = "4"
VER_JS = "3"
ASSET_VER = "23"

LANGS = ["en", "ko", "ja", "zh", "es", "fr", "de", "pt", "ru", "ar", "hi", "id"]
ORIG_LANGS = ["en", "ko"]
TR_LANGS = [l for l in LANGS if l not in ORIG_LANGS]
RTL = {"ar"}
OG_LOCALE = {"en": "en_US", "ko": "ko_KR", "ja": "ja_JP", "zh": "zh_CN", "es": "es_ES", "fr": "fr_FR", "de": "de_DE",
             "pt": "pt_BR", "ru": "ru_RU", "ar": "ar_AR", "hi": "hi_IN", "id": "id_ID"}
NATIVE = {"en": "English", "ko": "한국어", "ja": "日本語", "zh": "简体中文", "es": "Español", "fr": "Français",
          "de": "Deutsch", "pt": "Português", "ru": "Русский", "ar": "العربية", "hi": "हिन्दी", "id": "Bahasa Indonesia"}
UI_KEYS = ("skip", "home", "journal", "about", "contact", "privacy", "all_entries", "read", "eyebrow", "ai_label",
           "ai_text", "ai_link", "langs_label", "title_suffix", "list_title", "list_h1", "list_lede", "list_desc",
           "list_og_title", "blog_name", "all_posts", "crumb_journal", "home_aria")
POST_KEYS = ("title", "description", "abstract", "excerpt", "h1_html", "body")
I18N_DIR = ("scripts", "journal_i18n")


def esc(s):
    return html.escape(s, quote=True)


def post_url(slug, lang=None):
    """Original post URL; `lang` en/ko -> ?lang= variant, translation -> /journal/<lang>/<slug>/, None -> base."""
    if lang is None:
        return "%s/journal/%s/" % (SITE, slug)
    if lang in ORIG_LANGS:
        return "%s/journal/%s/?lang=%s" % (SITE, slug, lang)
    return "%s/journal/%s/%s/" % (SITE, lang, slug)


def list_url(lang=None):
    if lang is None:
        return SITE + "/journal/"
    if lang in ORIG_LANGS:
        return "%s/journal/?lang=%s" % (SITE, lang)
    return "%s/journal/%s/" % (SITE, lang)


def post_cluster(slug, langs):
    """[(hreflang, url)] for a post: x-default + en + ko + each available translation (LANGS order)."""
    out = [("x-default", post_url(slug)), ("en", post_url(slug, "en")), ("ko", post_url(slug, "ko"))]
    out += [(l, post_url(slug, l)) for l in LANGS if l in langs]
    return out


def list_cluster(langs):
    out = [("x-default", list_url()), ("en", list_url("en")), ("ko", list_url("ko"))]
    out += [(l, list_url(l)) for l in LANGS if l in langs]
    return out


def head_i18n(cluster, current):
    """hreflang links + og:locale / og:locale:alternate for a page whose own language is `current`
    ('en' for the original EN+KO page, whose alternate is ko)."""
    lines = ['<link rel="alternate" hreflang="%s" href="%s">' % (h, esc(u)) for h, u in cluster]
    present = [h for h, _ in cluster if h != "x-default"]
    lines.append('<meta property="og:locale" content="%s">' % OG_LOCALE[current])
    for h in present:
        if h != current:
            lines.append('<meta property="og:locale:alternate" content="%s">' % OG_LOCALE[h])
    return "\n".join(lines)


def langnav(cluster, current, label, skip_orig=False):
    """<nav> of language links. On original pages (skip_orig) en/ko are the in-page buttons, so only translations show."""
    items = []
    for h, u in cluster:
        if h == "x-default" or (skip_orig and h in ORIG_LANGS):
            continue
        cur = ' aria-current="true"' if h == current else ""
        items.append('<a class="lg"%s lang="%s" hreflang="%s" href="%s">%s</a>' % (cur, h, h, esc(u.replace(SITE, "")), NATIVE[h]))
    return '<nav class="langlist" aria-label="%s">\n  %s\n</nav>' % (esc(label), "\n  ".join(items))


def load(root):
    """Returns (ui, {slug: {lang: data}}, errors). Missing folder = no translations."""
    base = Path(root).joinpath(*I18N_DIR)
    ui, tr, errs = {}, {}, []
    if not base.is_dir():
        return ui, tr, errs
    f = base / "ui.json"
    if f.is_file():
        try:
            ui = json.loads(f.read_text(encoding="utf-8"))
        except ValueError as e:
            errs.append("journal_i18n/ui.json invalid: %s" % e)
    for d in sorted(p for p in base.iterdir() if p.is_dir()):
        for lang in TR_LANGS:
            f = d / ("%s.json" % lang)
            if not f.is_file():
                continue
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
            except ValueError as e:
                errs.append("journal_i18n/%s/%s.json invalid: %s" % (d.name, lang, e))
                continue
            missing = [k for k in POST_KEYS if not str(data.get(k, "")).strip()]
            if missing:
                errs.append("journal_i18n/%s/%s.json missing %s" % (d.name, lang, ", ".join(missing)))
                continue
            if "<script" in data["body"].lower() or "<script" in data["h1_html"].lower():
                errs.append("journal_i18n/%s/%s.json contains <script>" % (d.name, lang))
                continue
            tr.setdefault(d.name, {})[lang] = data
    bad = set()
    for slug, langs in tr.items():
        for lang in langs:
            miss = [k for k in UI_KEYS if not str(ui.get(lang, {}).get(k, "")).strip()]
            if miss and lang not in bad:
                bad.add(lang)
                errs.append("journal_i18n/ui.json[%s] missing %s" % (lang, ", ".join(miss)))
    if bad:  # build reports the error and renders nothing for these languages
        tr = {s: {l: d for l, d in v.items() if l not in bad} for s, v in tr.items()}
    return ui, tr, errs


def words(lang, body_html):
    """wordCount for a translation: whitespace words, or non-space characters for zh/ja (no word spaces)."""
    import re
    text = html.unescape(re.sub(r"<[^>]+>", " ", body_html))
    if lang in ("zh", "ja"):
        return len(re.sub(r"\s+", "", text))
    return len(text.split())


def _header(u, lang, current_list=False):
    return """<a class="skip" href="#main">%(skip)s</a>
<header class="topbar">
  <a class="logo ltr" href="/" aria-label="%(home_aria)s">ipe()</a>
  <div class="top-right">
    <nav aria-label="Primary"><a class="opt" href="/">%(home)s</a><a href="/journal/%(lang)s/"%(cur)s>%(journal)s</a></nav>
  </div>
</header>""" % dict(skip=esc(u["skip"]), home_aria=esc(u["home_aria"]), home=esc(u["home"]), journal=esc(u["journal"]),
                    lang=lang, cur=' aria-current="page"' if current_list else "")


def _footer(u, lang):
    return """<footer>
  <p class="sig ltr">ipe<span>()</span></p>
  <div class="foot">
    <p class="ltr">© 2026 ipe() · idle</p>
    <nav aria-label="Footer">
      <a class="ltr" href="/">ipe.rest</a>
      <a href="/journal/%s/">%s</a>
      <a href="/about/">%s</a>
      <a href="/contact/">%s</a>
      <a href="/privacy/">%s</a>
    </nav>
  </div>
</footer>""" % (lang, esc(u["journal"]), esc(u["about"]), esc(u["contact"]), esc(u["privacy"]))


def _common_head(lang, title, desc, canon):
    return """<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>%s</title>
<meta name="description" content="%s">
<meta name="author" content="ipe()">
<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">
<meta name="theme-color" content="#fbfcfe">
<link rel="canonical" href="%s">""" % (esc(title), esc(desc), canon)


def _assets_head():
    v = ASSET_VER
    return """<link rel="manifest" href="/manifest.webmanifest?v=%s">
<link rel="icon" type="image/png" sizes="192x192" href="/icon-192.png?v=%s">
<link rel="apple-touch-icon" href="/icon-180.png?v=%s">
<link rel="preload" href="/fonts/inter-400.woff2?v=%s" as="font" type="font/woff2" crossorigin>""" % (v, v, v, v)


def ld_script(obj):
    return '<script type="application/ld+json">\n%s\n</script>' % json.dumps(obj, ensure_ascii=False, indent=2)


def render_post(post, lang, ui, data, langs):
    """Full HTML of /journal/<lang>/<slug>/ ; `post` = the parsed original (journal_sync.load_post), `langs` = available translations."""
    u = ui[lang]
    slug = post["slug"]
    url = post_url(slug, lang)
    orig_url = post["url"]
    img = post["image"]
    cluster = post_cluster(slug, langs)
    modified = data.get("dateModified") or post["modified"]
    ld = dict(post["ld"])
    ld.pop("alternativeHeadline", None)
    ld.pop("workTranslation", None)
    ld.update({
        "@id": url + "#article", "headline": data["title"], "description": data["description"],
        "abstract": data["abstract"], "dateModified": modified, "inLanguage": lang, "url": url,
        "mainEntityOfPage": {"@type": "WebPage", "@id": url},
        "wordCount": words(lang, data["body"]),
        "isPartOf": {"@type": "Blog", "@id": "%s/journal/%s/#blog" % (SITE, lang), "name": u["blog_name"],
                     "url": list_url(lang)},
        "translationOfWork": {"@type": "BlogPosting", "@id": orig_url + "#article", "url": orig_url,
                              "inLanguage": ORIG_LANGS},
    })
    if data.get("keywords"):
        ld["keywords"] = data["keywords"]
    crumbs = {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "ipe()", "item": SITE + "/"},
        {"@type": "ListItem", "position": 2, "name": u["crumb_journal"], "item": list_url(lang)},
        {"@type": "ListItem", "position": 3, "name": data["title"]}]}
    img_url = esc(img.get("url", ""))
    tw = esc(data["title"])
    page_title = data["title"] + u["title_suffix"]
    parts = [
        '<!DOCTYPE html>',
        '<html lang="%s" dir="%s">' % (lang, "rtl" if lang in RTL else "ltr"),
        '<head>',
        _common_head(lang, page_title, data["description"], url),
        head_i18n(cluster, lang),
        _assets_head(),
        '',
        '<meta property="og:type" content="article">',
        '<meta property="og:site_name" content="ipe()">',
        '<meta property="og:title" content="%s">' % tw,
        '<meta property="og:description" content="%s">' % esc(data["description"]),
        '<meta property="og:url" content="%s">' % url,
        '<meta property="og:image" content="%s">' % img_url,
        '<meta property="og:image:width" content="%s">' % img.get("width", 1200),
        '<meta property="og:image:height" content="%s">' % img.get("height", 630),
        '<meta property="article:published_time" content="%s">' % post["published"],
        '<meta property="article:modified_time" content="%s">' % modified,
        '<meta property="article:section" content="%s">' % esc(post["category"]),
        '<meta property="article:author" content="ipe()">',
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % tw,
        '<meta name="twitter:description" content="%s">' % esc(data["description"]),
        '<meta name="twitter:image" content="%s">' % img_url,
        '',
        ld_script(ld),
        ld_script(crumbs),
        '<link rel="stylesheet" href="/journal/journal.css?v=%s">' % VER_CSS,
        '</head>',
        '<body>',
        _header(u, lang),
        '',
        '<main id="main">',
        '<article class="wrap">',
        '  <header class="post-head">',
        '    <p class="eyebrow"><i></i><span>%s · <time datetime="%s">%s</time></span></p>' % (esc(u["eyebrow"]), post["published"], post["published"]),
        '    <h1>%s</h1>' % data["h1_html"],
        '  </header>',
        '',
        '  <p class="ai-note" role="note"><strong>%s</strong> %s <a href="%s" hreflang="en">%s</a></p>' % (
            esc(u["ai_label"]), esc(u["ai_text"]), esc(post_url(slug).replace(SITE, "")), esc(u["ai_link"])),
        '',
        '  <div class="prose">',
        data["body"],
        '  </div>',
        '',
        '  <a class="back" href="/journal/%s/">%s</a>' % (lang, esc(u["all_entries"])),
        '  ' + langnav(cluster, lang, u["langs_label"]).replace("\n", "\n  "),
        '</article>',
        '</main>',
        '',
        _footer(u, lang),
        '<script src="/journal/journal.js?v=%s" defer></script>' % VER_JS,
        '</body>',
        '</html>',
        '',
    ]
    return "\n".join(parts)


def render_list_page(lang, ui, items, list_langs, blog_ld_extra=None):
    """/journal/<lang>/ . items = [(post, data)] newest first."""
    u = ui[lang]
    url = list_url(lang)
    cluster = list_cluster(list_langs)
    cards = []
    for p, d in items:
        cards.append("""    <li>
      <a class="post-card" href="/journal/%s/%s/">
        <p class="post-meta"><time datetime="%s">%s</time> · %s</p>
        <h2>%s</h2>
        <p class="excerpt">%s</p>
        <span class="more">%s</span>
      </a>
    </li>""" % (lang, p["slug"], p["published"], p["published"], esc(p["category"]),
                html.escape(d["title"], quote=False), html.escape(d["excerpt"], quote=False), esc(u["read"])))
    entries = []
    for p, d in items:
        e = {"@type": "BlogPosting", "@id": post_url(p["slug"], lang) + "#article", "headline": d["title"],
             "description": d["description"], "url": post_url(p["slug"], lang), "datePublished": p["published"],
             "dateModified": d.get("dateModified") or p["modified"], "inLanguage": lang}
        if p["image"].get("url"):
            e["image"] = p["image"]["url"]
        entries.append(e)
    graph = [
        {"@type": "Blog", "@id": "%s/journal/%s/#blog" % (SITE, lang), "name": u["blog_name"], "url": url,
         "description": u["list_desc"], "inLanguage": lang,
         "translationOfWork": {"@type": "Blog", "@id": SITE + "/journal/#blog", "url": list_url(), "inLanguage": ORIG_LANGS},
         "publisher": {"@type": "Organization", "@id": ORG_ID, "name": "ipe()", "url": SITE + "/"},
         "blogPost": entries},
        {"@type": "ItemList", "@id": "%s/journal/%s/#list" % (SITE, lang), "name": u["all_posts"],
         "itemListOrder": "https://schema.org/ItemListOrderDescending", "numberOfItems": len(items),
         "itemListElement": [{"@type": "ListItem", "position": i + 1, "url": post_url(p["slug"], lang), "name": d["title"]}
                             for i, (p, d) in enumerate(items)]},
    ]
    ldoc = {"@context": "https://schema.org", "@graph": graph}
    og = esc(u["list_og_title"])
    parts = [
        '<!DOCTYPE html>',
        '<html lang="%s" dir="%s">' % (lang, "rtl" if lang in RTL else "ltr"),
        '<head>',
        _common_head(lang, u["list_title"], u["list_desc"], url),
        head_i18n(cluster, lang),
        _assets_head(),
        '',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="ipe()">',
        '<meta property="og:title" content="%s">' % og,
        '<meta property="og:description" content="%s">' % esc(u["list_desc"]),
        '<meta property="og:url" content="%s">' % url,
        '<meta property="og:image" content="%s/og-image.png">' % SITE,
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % og,
        '<meta name="twitter:description" content="%s">' % esc(u["list_desc"]),
        '<meta name="twitter:image" content="%s/og-image.png">' % SITE,
        '',
        ld_script(ldoc),
        '<link rel="stylesheet" href="/journal/journal.css?v=%s">' % VER_CSS,
        '</head>',
        '<body>',
        _header(u, lang, current_list=True),
        '',
        '<main id="main" class="wrap">',
        '  <p class="eyebrow"><i></i><span>%s</span></p>' % esc(u["eyebrow"]),
        '  <h1 class="page-title">%s</h1>' % u["list_h1"],
        '  <p class="lede">%s</p>' % esc(u["list_lede"]),
        '  <p class="ai-note" role="note"><strong>%s</strong> %s</p>' % (esc(u["ai_label"]), esc(u["ai_text"])),
        '',
        '  <ul class="post-list">',
        "\n".join(cards),
        '  </ul>',
        '  ' + langnav(cluster, lang, u["langs_label"]).replace("\n", "\n  "),
        '</main>',
        '',
        _footer(u, lang),
        '<script src="/journal/journal.js?v=%s" defer></script>' % VER_JS,
        '</body>',
        '</html>',
        '',
    ]
    return "\n".join(parts)
