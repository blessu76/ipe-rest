def crumb_ld(trail):
    """BreadcrumbList; the last crumb is the current page (no `item`)."""
    out = []
    for i, (name, item) in enumerate(trail):
        e = {"@type": "ListItem", "position": i + 1, "name": name}
        if item:
            e["item"] = item
        out.append(e)
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": out}


def article_ld(post, lang, ui, data, langs):
    """BlogPosting node of /journal/<lang>/<slug>/ (also embedded in the x-default chooser page)."""
    u = ui[lang]
    slug = post["slug"]
    url = post_url(slug, lang)
    orig = post["original"]
    orig_url = post_url(slug, orig)
    modified = stamp(post, data.get("dateModified") or post["modified"])[0]
    ld = dict(post["ld"])
    ld.pop("alternativeHeadline", None)
    ld.pop("workTranslation", None)
    ld.pop("translationOfWork", None)
    ld.update({
        "@id": url + "#article", "headline": data["title"], "description": data["description"],
        "abstract": data["abstract"], "datePublished": stamp(post)[0], "dateModified": modified, "inLanguage": lang, "url": url,
        "mainEntityOfPage": {"@type": "WebPage", "@id": url},
        "wordCount": words(lang, data["body"]),
        "isPartOf": {"@type": "Blog", "@id": "%s/journal/%s/#blog" % (SITE, lang), "name": u["blog_name"],
                     "url": list_url(lang)},
    })
    if lang == orig:  # the original lists every other language as its translation
        ld["workTranslation"] = [{"@type": "BlogPosting", "@id": post_url(slug, l) + "#article", "url": post_url(slug, l),
                                  "inLanguage": l} for l in LANGS if l in langs and l != orig]
    else:
        ld["translationOfWork"] = {"@type": "BlogPosting", "@id": orig_url + "#article", "url": orig_url, "inLanguage": orig}
    if data.get("keywords"):
        ld["keywords"] = data["keywords"]
    return ld


def post_nav(u, lang, nav):
    """<nav> under a post: older/newer neighbour + the latest posts in the same language. `nav` = {"prev": (slug, title)|None,
    "next": (slug, title)|None, "related": [(slug, title), ...]} (journal_sync.nav_for). Plain links only — no dates, so adding
    a post never changes another post's dateModified / sitemap lastmod."""
    if not nav or not (nav.get("prev") or nav.get("next") or nav.get("related")):
        return ""
    def link(slug, title):
        return '<a href="/journal/%s/%s/">%s</a>' % (lang, slug, html.escape(title, quote=False))
    out = ['  <nav class="post-nav" aria-label="%s">' % esc(u["more_label"])]
    if nav.get("prev") or nav.get("next"):
        out.append('    <ul class="pn-step">')
        if nav.get("prev"):
            out.append('      <li class="pn-prev"><span>%s</span> %s</li>' % (esc(u["prev"]), link(*nav["prev"])))
        if nav.get("next"):
            out.append('      <li class="pn-next"><span>%s</span> %s</li>' % (esc(u["next"]), link(*nav["next"])))
        out.append('    </ul>')
    if nav.get("related"):
        out.append('    <p class="pn-head">%s</p>' % esc(u["latest"]))
        out.append('    <ul class="pn-list">')
        out += ['      <li>%s</li>' % link(*r) for r in nav["related"]]
        out.append('    </ul>')
    out.append('  </nav>')
    return "\n".join(out)


