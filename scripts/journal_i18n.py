def _common_head(lang, title, desc, canon):
    return """<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>%s</title>
<meta name="description" content="%s">
<meta name="author" content="ipe()">
<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">
<meta name="theme-color" content="#fbfcfe">
<link rel="canonical" href="%s">""" % (esc(title), esc(desc), canon)


def _assets_head():
    v = ASSET_VER
    return """<link rel="manifest" href="/manifest.webmanifest?v=%s">
<link rel="icon" type="image/png" sizes="192x192" href="/icon-192.png?v=%s">
<link rel="apple-touch-icon" href="/icon-180.png?v=%s">
<link rel="preload" href="/fonts/inter-400.woff2?v=%s" as="font" type="font/woff2" crossorigin>""" % (v, v, v, v)


def ld_script(obj):
    return '<script type="application/ld+json">\n%s\n</script>' % json.dumps(obj, ensure_ascii=False, indent=2)


def stamp(post, date=None):
    """(machine value, display text) for a post time. `date` = a modified date (default: published).
    With ipe:published-at (KST) -> ('2026-10-23T09:55+09:00', '2026-10-23 09:55'); without -> date only."""
    at = post.get("published_at") or ""
    d = date or post["published"]
    if at and d == at[:10]:
        return at, at[:10] + " " + at[11:16]
    return d, d


def time_tag(machine, label):
    """<time> for a post stamp. With a KST time (…+09:00) it is localised on the reader's device by shared/ipe-localtime.js;
    the static text (shown without JS) carries ' KST'. Date-only stamps stay plain."""
    if "T" in machine:
        return '<time datetime="%s" data-ipe-time dir="ltr">%s KST</time>' % (machine, label)
    return '<time datetime="%s" dir="ltr">%s</time>' % (machine, label)


def localtime_script():
    """Inline <script> with shared/ipe-localtime.js byte for byte (no whitespace added around it; see shared/README.md)."""
    src = (Path(__file__).resolve().parent.parent / "shared" / "ipe-localtime.js").read_bytes().decode("utf-8")
    return "<script>" + src + "</script>"


def crumb_ld(trail):
    """BreadcrumbList; the last crumb is the current page (no `item`)."""
    out = []
    for i, (name, item) in enumerate(trail):
        e = {"@type": "ListItem", "position": i + 1, "name": name}
        if item:
            e["item"] = item
        out.append(e)
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": out}


def article_ld(post, lang, ui, data, langs):
    """BlogPosting node of /journal/<lang>/<slug>/ (also embedded in the x-default chooser page)."""
    u = ui[lang]
    slug = post["slug"]
    url = post_url(slug, lang)
    orig = post["original"]
    orig_url = post_url(slug, orig)
    modified = stamp(post, data.get("dateModified") or post["modified"])[0]
    ld = dict(post["ld"])
    ld.pop("alternativeHeadline", None)
    ld.pop("workTranslation", None)
    ld.pop("translationOfWork", None)
    ld.update({
        "@id": url + "#article", "headline": data["title"], "description": data["description"],
        "abstract": data["abstract"], "datePublished": stamp(post)[0], "dateModified": modified, "inLanguage": lang, "url": url,
        "mainEntityOfPage": {"@type": "WebPage", "@id": url},
        "wordCount": words(lang, data["body"]),
        "isPartOf": {"@type": "Blog", "@id": "%s/journal/%s/#blog" % (SITE, lang), "name": u["blog_name"],
                     "url": list_url(lang)},
    })
    if lang == orig:  # the original lists every other language as its translation
        ld["workTranslation"] = [{"@type": "BlogPosting", "@id": post_url(slug, l) + "#article", "url": post_url(slug, l),
                                  "inLanguage": l} for l in LANGS if l in langs and l != orig]
    else:
        ld["translationOfWork"] = {"@type": "BlogPosting", "@id": orig_url + "#article", "url": orig_url, "inLanguage": orig}
    if data.get("keywords"):
        ld["keywords"] = data["keywords"]
    return ld


def render_post(post, lang, ui, data, langs):
    """Full HTML of /journal/<lang>/<slug>/ ; `post` = parsed source (journal_sync.load_post), `langs` = available languages."""
    u = ui[lang]
    slug = post["slug"]
    url = post_url(slug, lang)
    orig = post["original"]
    orig_url = post_url(slug, orig)
    img = post["image"]
    cluster = post_cluster(slug, langs)
    modified = stamp(post, data.get("dateModified") or post["modified"])[0]
    ld = article_ld(post, lang, ui, data, langs)
    crumbs = crumb_ld([("ipe()", SITE + "/"), (u["crumb_journal"], list_url(lang)), (data["title"], None)])
    img_url = esc(img.get("url", ""))
    tw = esc(data["title"])
    page_title = data["title"] + u["title_suffix"]
    parts = [
        '<!DOCTYPE html>',
        '<html lang="%s" dir="%s">' % (lang, "rtl" if lang in RTL else "ltr"),
        '<head>',
        _common_head(lang, page_title, data["description"], url),
        head_i18n(cluster, lang),
        _assets_head(),
        '',
        '<meta property="og:type" content="article">',
        '<meta property="og:site_name" content="ipe()">',
        '<meta property="og:title" content="%s">' % tw,
        '<meta property="og:description" content="%s">' % esc(data["description"]),
        '<meta property="og:url" content="%s">' % url,
        '<meta property="og:image" content="%s">' % img_url,
        '<meta property="og:image:width" content="%s">' % img.get("width", 1200),
        '<meta property="og:image:height" content="%s">' % img.get("height", 630),
        '<meta property="article:published_time" content="%s">' % stamp(post)[0],
        '<meta property="article:modified_time" content="%s">' % modified,
        '<meta property="article:section" content="%s">' % esc(post["category"]),
        '<meta property="article:author" content="ipe()">',
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % tw,
        '<meta name="twitter:description" content="%s">' % esc(data["description"]),
        '<meta name="twitter:image" content="%s">' % img_url,
        '',
        ld_script(ld),
        ld_script(crumbs),
        '<link rel="stylesheet" href="/journal/journal.css?v=%s">' % VER_CSS,
        '</head>',
        '<body>',
        _header(u, lang, cluster),
        '',
        '<main id="main">',
        '<article class="wrap">',
        '  <header class="post-head">',
        '    <p class="eyebrow"><i></i><span>%s · %s</span></p>' % (esc(u["eyebrow"]), time_tag(*stamp(post))),
        '    <h1>%s</h1>' % data["h1_html"],
        '  </header>',
        '',
        ('  <p class="ai-note" role="note"><strong>%s</strong> %s <a href="%s" hreflang="%s">%s</a></p>' % (
            esc(u["ai_label"]), esc(u["ai_text"]), esc(orig_url.replace(SITE, "")), orig, esc(u["ai_link"]))
         if lang in TR_LANGS else ''),
        '',
        '  <div class="prose">',
        data["body"],
        '  </div>',
        '',
        '  <a class="back" href="/journal/%s/">%s</a>' % (lang, esc(u["all_entries"])),
        '</article>',
        '</main>',
        '',
        _footer(u, lang),
        '<script src="/journal/journal.js?v=%s" defer></script>' % VER_JS,
        localtime_script(),
        '</body>',
        '</html>',
        '',
    ]
    return "\n".join(parts)


def _post_card(href, p, d, u):
    return """    <li>
      <a class="post-card" href="%s">
        <p class="post-meta">%s · %s</p>
        <h2>%s</h2>
        <p class="excerpt">%s</p>
        <span class="more">%s</span>
      </a>
    </li>""" % (href, time_tag(*stamp(p)), esc(p["category"]),
                html.escape(d["title"], quote=False), html.escape(d["excerpt"], quote=False), esc(u["read"]))


CHOOSE_TITLE = " · choose your language"
CHOOSE_DESC = "Choose your language: "


def render_list_page(lang, ui, items, list_langs):
    """/journal/<lang>/ . items = [(post, data)] newest first."""
    u = ui[lang]
    url = list_url(lang)
    cluster = list_cluster(list_langs)
    cards = [_post_card("/journal/%s/%s/" % (lang, p["slug"]), p, d, u) for p, d in items]
    entries = []
    for p, d in items:
        e = {"@type": "BlogPosting", "@id": post_url(p["slug"], lang) + "#article", "headline": d["title"],
             "description": d["description"], "url": post_url(p["slug"], lang), "datePublished": stamp(p)[0],
             "dateModified": stamp(p, d.get("dateModified") or p["modified"])[0], "inLanguage": lang}
        if p["image"].get("url"):
            e["image"] = p["image"]["url"]
        entries.append(e)
    graph = [
        {"@type": "Blog", "@id": "%s/journal/%s/#blog" % (SITE, lang), "name": u["blog_name"], "url": url,
         "description": u["list_desc"], "inLanguage": lang,
         "publisher": {"@type": "Organization", "@id": ORG_ID, "name": "ipe()", "url": SITE + "/"},
         "isPartOf": {"@id": "%s/%s/#website" % (SITE, lang)},
         "blogPost": entries},
        {"@type": "ItemList", "@id": "%s/journal/%s/#list" % (SITE, lang), "name": u["all_posts"],
         "itemListOrder": "https://schema.org/ItemListOrderDescending", "numberOfItems": len(items),
         "itemListElement": [{"@type": "ListItem", "position": i + 1, "url": post_url(p["slug"], lang), "name": d["title"]}
                             for i, (p, d) in enumerate(items)]},
    ]
    ldoc = {"@context": "https://schema.org", "@graph": graph}
    crumbs = crumb_ld([("ipe()", SITE + "/"), (u["crumb_journal"], None)])
    og = esc(u["list_og_title"])
    parts = [
        '<!DOCTYPE html>',
        '<html lang="%s" dir="%s">' % (lang, "rtl" if lang in RTL else "ltr"),
        '<head>',
        _common_head(lang, u["list_title"], u["list_desc"], url),
        head_i18n(cluster, lang),
        _assets_head(),
        '',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="ipe()">',
        '<meta property="og:title" content="%s">' % og,
        '<meta property="og:description" content="%s">' % esc(u["list_desc"]),
        '<meta property="og:url" content="%s">' % url,
        '<meta property="og:image" content="%s/og-image.png">' % SITE,
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % og,
        '<meta name="twitter:description" content="%s">' % esc(u["list_desc"]),
        '<meta name="twitter:image" content="%s/og-image.png">' % SITE,
        '',
        ld_script(ldoc),
        ld_script(crumbs),
        '<link rel="stylesheet" href="/journal/journal.css?v=%s">' % VER_CSS,
        '</head>',
        '<body>',
        _header(u, lang, cluster, current_list=True),
        '',
        '<main id="main" class="wrap">',
        '  <p class="eyebrow"><i></i><span>%s</span></p>' % esc(u["eyebrow"]),
        '  <h1 class="page-title">%s</h1>' % u["list_h1"],
        '  <p class="lede">%s</p>' % esc(u["list_lede"]),
        ('  <p class="ai-note" role="note"><strong>%s</strong> %s <a href="/journal/en/" hreflang="en">English</a> · <a href="/journal/ko/" hreflang="ko">한국어</a></p>'
         % (esc(u["ai_label"]), esc(u["ai_text"]))
         if lang in TR_LANGS else ''),
        '',
        '  <ul class="post-list">',
        "\n".join(cards),
        '  </ul>',
        '</main>',
        '',
        _footer(u, lang),
        '<script src="/journal/journal.js?v=%s" defer></script>' % VER_JS,
        localtime_script(),
        '</body>',
        '</html>',
        '',
    ]
    return "\n".join(parts)


def _chooser_head(title, desc, canon, cluster, og_type, og_locale, ld_objs):
    # x-default chooser shares its text with the /en/ page; keep title/description distinct (duplicate-metadata SEO finding)
    title, desc = title + CHOOSE_TITLE, CHOOSE_DESC + desc
    return [
        '<!DOCTYPE html>', '<html lang="%s" dir="ltr" data-chooser>' % og_locale[:2], '<head>',
        _common_head("en", title, desc, canon),
        "\n".join('<link rel="alternate" hreflang="%s" href="%s">' % (h, esc(u)) for h, u in cluster),
        _assets_head(), '',
        '<meta property="og:type" content="%s">' % og_type,
        '<meta property="og:site_name" content="ipe()">',
        '<meta property="og:title" content="%s">' % esc(title),
        '<meta property="og:description" content="%s">' % esc(desc),
        '<meta property="og:url" content="%s">' % canon,
        '<meta property="og:locale" content="%s">' % og_locale,
        '<meta property="og:image" content="%s/og-image.png">' % SITE,
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % esc(title),
        '<meta name="twitter:description" content="%s">' % esc(desc),
        '<meta name="twitter:image" content="%s/og-image.png">' % SITE, '',
    ] + [ld_script(o) for o in ld_objs] + ['<link rel="stylesheet" href="/journal/journal.css?v=%s">' % VER_CSS, '</head>']


