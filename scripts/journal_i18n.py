"""Journal translations (10 languages) for ipe.rest — stdlib only. Used by journal_sync.py.

URL rule (static, never ?lang=) — all 12 languages are equal:
    post         /journal/<lang>/<slug>/     lang = en ko ja zh es fr de pt ru ar hi id
    list         /journal/<lang>/
    x-default    /journal/<slug>/ and /journal/   language-chooser pages (generated; self-canonical)
The post's source language is `ipe:original` (en | ko) in scripts/journal_src/<slug>.html. en and ko are generated from that
bilingual source; the other 10 come from scripts/journal_i18n/<slug>/<lang>.json. Only those 10 get the "AI translation" note.

Translation source (hand/machine-drafted, one file per post+language, plus UI strings for all 12 languages):
    scripts/journal_i18n/ui.json
    scripts/journal_i18n/<slug>/<lang>.json   title, description, abstract, excerpt, h1_html, body (HTML), [keywords, dateModified]

Everything under journal/ except journal.css/js is GENERATED by journal_sync.py from those files — never edit it by hand.
"""
import html
import json
from pathlib import Path

SITE = "https://ipe.rest"
ORG_ID = SITE + "/#organization"
VER_CSS = "9"
VER_JS = "7"
ASSET_VER = "23"

LANGS = ["en", "ko", "ja", "zh", "es", "fr", "de", "pt", "ru", "ar", "hi", "id"]
ORIG_LANGS = ["en", "ko"]
TR_LANGS = [l for l in LANGS if l not in ORIG_LANGS]
RTL = {"ar"}
OG_LOCALE = {"en": "en_US", "ko": "ko_KR", "ja": "ja_JP", "zh": "zh_CN", "es": "es_ES", "fr": "fr_FR", "de": "de_DE",
             "pt": "pt_BR", "ru": "ru_RU", "ar": "ar_AR", "hi": "hi_IN", "id": "id_ID"}
NATIVE = {"en": "English", "ko": "한국어", "ja": "日本語", "zh": "简体中文", "es": "Español", "fr": "Français",
          "de": "Deutsch", "pt": "Português", "ru": "Русский", "ar": "العربية", "hi": "हिन्दी", "id": "Bahasa Indonesia"}
UI_KEYS = ("skip", "home", "journal", "about", "contact", "privacy", "all_entries", "read", "eyebrow",
           "langs_label", "title_suffix", "list_title", "list_h1", "list_lede", "list_desc",
           "list_og_title", "blog_name", "all_posts", "crumb_journal", "home_aria")
AI_KEYS = ("ai_label", "ai_text", "ai_link")  # only the machine-translated languages
POST_KEYS = ("title", "description", "abstract", "excerpt", "h1_html", "body")
I18N_DIR = ("scripts", "journal_i18n")


def esc(s):
    return html.escape(s, quote=True)


def post_url(slug, lang=None):
    """/journal/<lang>/<slug>/ ; lang None -> the x-default chooser page /journal/<slug>/."""
    if lang is None:
        return "%s/journal/%s/" % (SITE, slug)
    return "%s/journal/%s/%s/" % (SITE, lang, slug)


def list_url(lang=None):
    if lang is None:
        return SITE + "/journal/"
    return "%s/journal/%s/" % (SITE, lang)


def post_cluster(slug, langs):
    """[(hreflang, url)] for a post: x-default + each available language (LANGS order)."""
    return [("x-default", post_url(slug))] + [(l, post_url(slug, l)) for l in LANGS if l in langs]


def list_cluster(langs):
    return [("x-default", list_url())] + [(l, list_url(l)) for l in LANGS if l in langs]


def head_i18n(cluster, current):
    """hreflang links + og:locale / og:locale:alternate for a page whose own language is `current`
    ('en' for the original EN+KO page, whose alternate is ko)."""
    lines = ['<link rel="alternate" hreflang="%s" href="%s">' % (h, esc(u)) for h, u in cluster]
    present = [h for h, _ in cluster if h != "x-default"]
    lines.append('<meta property="og:locale" content="%s">' % OG_LOCALE[current])
    for h in present:
        if h != current:
            lines.append('<meta property="og:locale:alternate" content="%s">' % OG_LOCALE[h])
    return "\n".join(lines)


GLOBE = ('<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" aria-hidden="true"><circle cx="12" cy="12" r="9"/>'
         '<path d="M3 12h18M12 3c2.5 2.5 3.8 5.8 3.8 9s-1.3 6.5-3.8 9c-2.5-2.5-3.8-5.8-3.8-9S9.5 5.5 12 3z"/></svg>')


def langselect(cluster, current, label):
    """Header language select (same look/behaviour as the main page). Options are only the languages that exist for this
    page (cluster), each a real URL; `current` None = x-default chooser (nothing selected yet). journal.js navigates on change."""
    opts = []
    if current is None:
        opts.append('<option value="" selected disabled>%s</option>' % esc(label))
    for h, u in cluster:
        if h == "x-default":
            continue
        opts.append('<option value="%s" lang="%s"%s>%s</option>' % (esc(u.replace(SITE, "")), h, " selected" if h == current else "", h.upper()))
    return ('<label class="language"><span class="sr-only">%s</span>%s<select class="lang" data-lang-select aria-label="%s">\n      %s\n    </select></label>'
            % (esc(label), GLOBE, esc(label), "\n      ".join(opts)))


def load(root):
    """Returns (ui, {slug: {lang: data}}, errors). Missing folder = no translations."""
    base = Path(root).joinpath(*I18N_DIR)
    ui, tr, errs = {}, {}, []
    if not base.is_dir():
        return ui, tr, errs
    f = base / "ui.json"
    if f.is_file():
        try:
            ui = json.loads(f.read_text(encoding="utf-8"))
        except ValueError as e:
            errs.append("journal_i18n/ui.json invalid: %s" % e)
    for d in sorted(p for p in base.iterdir() if p.is_dir()):
        for lang in TR_LANGS:
            f = d / ("%s.json" % lang)
            if not f.is_file():
                continue
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
            except ValueError as e:
                errs.append("journal_i18n/%s/%s.json invalid: %s" % (d.name, lang, e))
                continue
            e = check_post_data("journal_i18n/%s/%s.json" % (d.name, lang), data)
            if e:
                errs += e
                continue
            tr.setdefault(d.name, {})[lang] = data
    return ui, tr, errs


def check_post_data(label, data):
    """Errors for one language's post data dict (shared by en/ko sources and translation JSON)."""
    errs = []
    missing = [k for k in POST_KEYS if not str(data.get(k, "")).strip()]
    if missing:
        errs.append("%s missing %s" % (label, ", ".join(missing)))
    elif "<script" in data["body"].lower() or "<script" in data["h1_html"].lower():
        errs.append("%s contains <script>" % label)
    return errs


def ui_errors(ui, langs):
    """(errors, bad_langs): every language used needs the UI strings (AI-note keys only for machine-translated ones)."""
    errs, bad = [], set()
    for lang in LANGS:
        if lang not in langs:
            continue
        keys = UI_KEYS + (AI_KEYS if lang in TR_LANGS else ())
        miss = [k for k in keys if not str(ui.get(lang, {}).get(k, "")).strip()]
        if miss:
            bad.add(lang)
            errs.append("journal_i18n/ui.json[%s] missing %s" % (lang, ", ".join(miss)))
    return errs, bad


def words(lang, body_html):
    """wordCount for a translation: whitespace words, or non-space characters for zh/ja (no word spaces)."""
    import re
    text = html.unescape(re.sub(r"<[^>]+>", " ", body_html))
    if lang in ("zh", "ja"):
        return len(re.sub(r"\s+", "", text))
    return len(text.split())


def _header(u, lang, cluster, current_list=False):
    return """<a class="skip" href="#main">%(skip)s</a>
<header class="topbar">
  <a class="logo ltr" href="/%(lang)s/" aria-label="%(home_aria)s">ipe()</a>
  <div class="top-right">
    <nav aria-label="Primary"><a class="opt" href="/%(lang)s/">%(home)s</a><a href="/journal/%(lang)s/"%(cur)s>%(journal)s</a></nav>
    %(select)s
  </div>
</header>""" % dict(select=langselect(cluster, lang, u["langs_label"]), skip=esc(u["skip"]), home_aria=esc(u["home_aria"]), home=esc(u["home"]), journal=esc(u["journal"]),
                    lang=lang, cur=' aria-current="page"' if current_list else "")


